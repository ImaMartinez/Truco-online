-- 7) La sala representa la espera por un segundo jugador, NO una partida incompleta.
CREATE TABLE truco_arena_der.sala (
  id_sala BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  codigo CHAR(9) NOT NULL,
  id_anfitrion BIGINT NOT NULL,
  id_mazo_anfitrion BIGINT NOT NULL,
  id_invitado BIGINT NULL,
  id_mazo_invitado BIGINT NULL,
  id_partida BIGINT NULL,
  estado VARCHAR(12) NOT NULL DEFAULT 'ESPERANDO',
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_expiracion TIMESTAMPTZ NOT NULL,
  fecha_union TIMESTAMPTZ NULL,
  CONSTRAINT pk_sala PRIMARY KEY (id_sala),
  CONSTRAINT uq_sala_codigo UNIQUE (codigo),
  CONSTRAINT uq_sala_partida UNIQUE (id_partida),
  CONSTRAINT ck_sala_codigo CHECK (codigo ~ '^[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}$'),
  CONSTRAINT ck_sala_estado CHECK (estado IN ('ESPERANDO','EN_CURSO','FINALIZADA','CANCELADA','EXPIRADA')),
  CONSTRAINT ck_sala_fechas CHECK (
    fecha_expiracion > fecha_creacion AND
    (fecha_union IS NULL OR fecha_union >= fecha_creacion)
  ),
  CONSTRAINT ck_sala_jugadores_distintos CHECK (
    id_invitado IS NULL OR id_invitado <> id_anfitrion
  ),
  CONSTRAINT ck_sala_pareja_invitado CHECK (
    (id_invitado IS NULL AND id_mazo_invitado IS NULL)
    OR (id_invitado IS NOT NULL AND id_mazo_invitado IS NOT NULL)
