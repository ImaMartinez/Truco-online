CREATE SCHEMA IF NOT EXISTS truco_arena_der;
SET LOCAL search_path TO truco_arena_der, public;

CREATE TABLE jugador (
  id_jugador BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  alias VARCHAR(40) NOT NULL,
  fecha_alta TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  fecha_archivo TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  CONSTRAINT pk_jugador PRIMARY KEY (id_jugador),
  CONSTRAINT uq_jugador_alias UNIQUE (alias),
  CONSTRAINT ck_jugador_alias CHECK (CHAR_LENGTH(TRIM(alias)) BETWEEN 1 AND 40 AND CHAR_LENGTH(alias) = CHAR_LENGTH(TRIM(alias))),
  CONSTRAINT ck_jugador_fechas CHECK (fecha_archivo IS NULL OR fecha_archivo >= fecha_alta)
);

CREATE TABLE carta (
  id_carta CHAR(6) NOT NULL,
  nombre VARCHAR(60) NOT NULL,
  palo VARCHAR(7) NOT NULL,
  numero SMALLINT NOT NULL,
  ataque_base SMALLINT NOT NULL,
  vida_base SMALLINT NOT NULL,
  costo_energia SMALLINT NOT NULL,
  jerarquia_truco SMALLINT NOT NULL,
  CONSTRAINT pk_carta PRIMARY KEY (id_carta),
  CONSTRAINT uq_carta_palo_numero UNIQUE (palo, numero),
  CONSTRAINT ck_carta_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) BETWEEN 1 AND 60 AND CHAR_LENGTH(nombre)=CHAR_LENGTH(TRIM(nombre))),
  CONSTRAINT ck_carta_palo CHECK (palo IN ('espadas','bastos','oros','copas')),
  CONSTRAINT ck_carta_numero CHECK (numero BETWEEN 1 AND 7 OR numero BETWEEN 10 AND 12),
  CONSTRAINT ck_carta_stats CHECK (ataque_base > 0 AND vida_base > 0 AND costo_energia BETWEEN 1 AND 5),
  CONSTRAINT ck_carta_jerarquia CHECK (jerarquia_truco BETWEEN 1 AND 14),
  CONSTRAINT ck_carta_codigo_tipo CHECK (
    id_carta = CONCAT(
      CASE palo WHEN 'espadas' THEN 'ESP' WHEN 'bastos' THEN 'BAS'
                WHEN 'oros' THEN 'ORO' WHEN 'copas' THEN 'COP' END,
      '-', LPAD(numero::text,2,'0')
    )
  )
);

CREATE TABLE coleccion_jugador (
  id_jugador BIGINT NOT NULL,
  id_carta CHAR(6) NOT NULL,
  cantidad INTEGER NOT NULL,
  CONSTRAINT pk_coleccion_jugador PRIMARY KEY (id_jugador, id_carta),
  CONSTRAINT ck_coleccion_cantidad CHECK (cantidad > 0),
  CONSTRAINT fk_coleccion_jugador FOREIGN KEY (id_jugador) REFERENCES jugador(id_jugador) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_coleccion_carta FOREIGN KEY (id_carta) REFERENCES carta(id_carta) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE mazo (
  id_mazo BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_jugador BIGINT NOT NULL,
  nombre VARCHAR(60) NOT NULL,
  descripcion VARCHAR(200) NOT NULL,
  fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  fecha_archivo TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  CONSTRAINT pk_mazo PRIMARY KEY (id_mazo),
  CONSTRAINT uq_mazo_dueno_nombre UNIQUE (id_jugador, nombre),
  CONSTRAINT ck_mazo_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) BETWEEN 1 AND 60 AND CHAR_LENGTH(nombre)=CHAR_LENGTH(TRIM(nombre))),
  CONSTRAINT ck_mazo_fechas CHECK (fecha_archivo IS NULL OR fecha_archivo >= fecha_creacion),
  CONSTRAINT fk_mazo_jugador FOREIGN KEY (id_jugador) REFERENCES jugador(id_jugador) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE mazo_carta (
  id_mazo BIGINT NOT NULL,
  id_carta CHAR(6) NOT NULL,
  cantidad SMALLINT NOT NULL,
  CONSTRAINT pk_mazo_carta PRIMARY KEY (id_mazo, id_carta),
  CONSTRAINT ck_mazo_carta_cantidad CHECK (cantidad BETWEEN 1 AND 2),
  CONSTRAINT fk_mazo_carta_mazo FOREIGN KEY (id_mazo) REFERENCES mazo(id_mazo) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_mazo_carta_carta FOREIGN KEY (id_carta) REFERENCES carta(id_carta) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE partida (
  id_partida BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  fecha_inicio TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  fecha_fin TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  motivo_cierre VARCHAR(16) NULL,
  ganador_posicion SMALLINT NULL,
  version BIGINT NOT NULL,
  CONSTRAINT pk_partida PRIMARY KEY (id_partida),
  CONSTRAINT ck_partida_version CHECK (version >= 1),
  CONSTRAINT ck_partida_ganador CHECK (ganador_posicion IS NULL OR ganador_posicion IN (1,2)),
  CONSTRAINT ck_partida_motivo CHECK (motivo_cierre IS NULL OR motivo_cierre IN ('VIDA_CERO','LIMITE_TURNOS')),
  CONSTRAINT ck_partida_cierre CHECK (
    (fecha_fin IS NULL AND motivo_cierre IS NULL AND ganador_posicion IS NULL)
    OR (fecha_fin IS NOT NULL AND fecha_fin >= fecha_inicio
        AND motivo_cierre IS NOT NULL
        AND (motivo_cierre <> 'VIDA_CERO' OR ganador_posicion IS NOT NULL))
  )
);

CREATE TABLE participante_partida (
  id_participante BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_partida BIGINT NOT NULL,
  posicion SMALLINT NOT NULL,
  id_mazo BIGINT NOT NULL,
  vida_heroe SMALLINT NOT NULL,
  CONSTRAINT pk_participante_partida PRIMARY KEY (id_participante),
  CONSTRAINT uq_participante_posicion UNIQUE (id_partida, posicion),
  CONSTRAINT uq_participante_mazo UNIQUE (id_partida, id_mazo),
  CONSTRAINT ck_participante_posicion CHECK (posicion IN (1,2)),
  CONSTRAINT ck_participante_vida CHECK (vida_heroe BETWEEN 0 AND 20),
  CONSTRAINT fk_participante_partida FOREIGN KEY (id_partida) REFERENCES partida(id_partida) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_participante_mazo FOREIGN KEY (id_mazo) REFERENCES mazo(id_mazo) ON DELETE RESTRICT ON UPDATE RESTRICT
);

-- FK circular: se agrega después de que exista participante_partida.
ALTER TABLE partida
  ADD CONSTRAINT fk_partida_ganador
  FOREIGN KEY (id_partida, ganador_posicion)
  REFERENCES participante_partida (id_partida, posicion)
  ON DELETE RESTRICT ON UPDATE RESTRICT;

CREATE TABLE copia_carta_partida (
  id_copia BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_participante BIGINT NOT NULL,
  id_carta CHAR(6) NOT NULL,
  posicion_original SMALLINT NOT NULL,
  zona VARCHAR(8) NOT NULL,
  vida_actual SMALLINT NULL,
  CONSTRAINT pk_copia_carta_partida PRIMARY KEY (id_copia),
  CONSTRAINT uq_copia_posicion UNIQUE (id_participante, posicion_original),
  CONSTRAINT ck_copia_posicion CHECK (posicion_original BETWEEN 1 AND 12),
  CONSTRAINT ck_copia_zona_vida CHECK (
     (zona IN ('MAZO','MANO') AND vida_actual IS NULL)
     OR (zona='CAMPO' AND vida_actual IS NOT NULL AND vida_actual > 0)
     OR (zona='DESCARTE' AND vida_actual IS NOT NULL AND vida_actual = 0)
  ),
  CONSTRAINT fk_copia_participante FOREIGN KEY (id_participante) REFERENCES participante_partida(id_participante) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_copia_carta FOREIGN KEY (id_carta) REFERENCES carta(id_carta) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE turno (
  id_turno BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_partida BIGINT NOT NULL,
  numero_global SMALLINT NOT NULL,
  energia_disponible SMALLINT NOT NULL,
  fecha_apertura TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  fecha_cierre TIMESTAMP(6) WITHOUT TIME ZONE NULL,
  CONSTRAINT pk_turno PRIMARY KEY (id_turno),
  CONSTRAINT uq_turno_global UNIQUE (id_partida, numero_global),
  CONSTRAINT ck_turno_numero CHECK (numero_global BETWEEN 1 AND 30),
  CONSTRAINT ck_turno_energia CHECK (energia_disponible BETWEEN 0 AND LEAST(5, FLOOR((numero_global+1)/2))),
  CONSTRAINT ck_turno_fechas CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_apertura),
  CONSTRAINT fk_turno_partida FOREIGN KEY (id_partida) REFERENCES partida(id_partida) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE solicitud_operacion (
  clave_reintento UUID NOT NULL,
  id_partida BIGINT NOT NULL,
  tipo_operacion VARCHAR(20) NOT NULL,
  hash_parametros CHAR(64) NOT NULL,
  version_resultante BIGINT NOT NULL,
  fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  CONSTRAINT pk_solicitud_operacion PRIMARY KEY (clave_reintento),
  CONSTRAINT uq_solicitud_version UNIQUE (id_partida, version_resultante),
  CONSTRAINT ck_solicitud_uuid CHECK (clave_reintento::text ~ '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'),
  CONSTRAINT ck_solicitud_hash CHECK (hash_parametros ~ '^[0-9a-fA-F]{64}$'),
  CONSTRAINT ck_solicitud_tipo CHECK (tipo_operacion IN ('CREAR_PARTIDA','INVOCAR','ATACAR','FINALIZAR_TURNO')),
  CONSTRAINT ck_solicitud_version CHECK (version_resultante >= 1 AND (tipo_operacion <> 'CREAR_PARTIDA' OR version_resultante=1)),
  CONSTRAINT fk_solicitud_partida FOREIGN KEY (id_partida) REFERENCES partida(id_partida) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE jugada (
  id_jugada BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_turno BIGINT NOT NULL,
  orden_en_turno INTEGER NOT NULL,
  clave_reintento UUID NOT NULL,
  CONSTRAINT pk_jugada PRIMARY KEY (id_jugada),
  CONSTRAINT uq_jugada_orden UNIQUE (id_turno, orden_en_turno),
  CONSTRAINT uq_jugada_solicitud UNIQUE (clave_reintento),
  CONSTRAINT ck_jugada_orden CHECK (orden_en_turno > 0),
  CONSTRAINT fk_jugada_turno FOREIGN KEY (id_turno) REFERENCES turno(id_turno) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_jugada_solicitud FOREIGN KEY (clave_reintento) REFERENCES solicitud_operacion(clave_reintento) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE invocacion (
  id_jugada BIGINT NOT NULL,
  id_copia BIGINT NOT NULL,
  CONSTRAINT pk_invocacion PRIMARY KEY (id_jugada),
  CONSTRAINT uq_invocacion_copia UNIQUE (id_copia),
  CONSTRAINT fk_invocacion_jugada FOREIGN KEY (id_jugada) REFERENCES jugada(id_jugada) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_invocacion_copia FOREIGN KEY (id_copia) REFERENCES copia_carta_partida(id_copia) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE ataque (
  id_jugada BIGINT NOT NULL,
  id_copia_atacante BIGINT NOT NULL,
  id_copia_objetivo BIGINT NULL,
  id_participante_objetivo BIGINT NULL,
  vida_previa_atacante SMALLINT NOT NULL,
  vida_previa_objetivo SMALLINT NOT NULL,
  CONSTRAINT pk_ataque PRIMARY KEY (id_jugada),
  CONSTRAINT ck_ataque_objetivo_xor CHECK (
    (id_copia_objetivo IS NOT NULL AND id_participante_objetivo IS NULL)
    OR (id_copia_objetivo IS NULL AND id_participante_objetivo IS NOT NULL)
  ),
  CONSTRAINT ck_ataque_vida CHECK (vida_previa_atacante > 0 AND vida_previa_objetivo > 0
    AND (id_participante_objetivo IS NULL OR vida_previa_objetivo <= 20)),
  CONSTRAINT ck_ataque_copias CHECK (id_copia_objetivo IS NULL OR id_copia_objetivo <> id_copia_atacante),
  CONSTRAINT fk_ataque_jugada FOREIGN KEY (id_jugada) REFERENCES jugada(id_jugada) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_ataque_atacante FOREIGN KEY (id_copia_atacante) REFERENCES copia_carta_partida(id_copia) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_ataque_objetivo_carta FOREIGN KEY (id_copia_objetivo) REFERENCES copia_carta_partida(id_copia) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_ataque_objetivo_heroe FOREIGN KEY (id_participante_objetivo) REFERENCES participante_partida(id_participante) ON DELETE RESTRICT ON UPDATE RESTRICT
);


