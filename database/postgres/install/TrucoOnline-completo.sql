-- TRUCO ARENA | DER / MR | PostgreSQL (Supabase)
-- SOLO ESTRUCTURA: 13 tablas, 65 columnas, FK, PK, UNIQUE y CHECK.
-- No modifica el schema public ni las tablas existentes del juego.
-- Crea schema privado truco_arena_der, para visualizar relaciones
-- en Database > Schema Visualizer, seleccionando ese schema.
